-- WAREHOUSE CONTROL shared database schema for Supabase
-- Run the whole script in Supabase Dashboard -> SQL Editor -> New query.

create table if not exists public.inventory_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.inventory_items (
  id bigint generated by default as identity primary key,
  category text not null default '포스',
  barcode text not null default '',
  model text not null default '',
  maker text not null default '',
  store text not null default '',
  channel text not null default '',
  stock integer not null default 0 check (stock >= 0),
  repair integer not null default 0 check (repair >= 0),
  vendor integer not null default 0 check (vendor >= 0),
  product integer not null default 0 check (product >= 0),
  shipped integer not null default 0 check (shipped >= 0),
  disposal integer not null default 0 check (disposal >= 0),
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory_transactions (
  id bigint generated by default as identity primary key,
  tx_date date not null default current_date,
  type text not null,
  category text not null default '포스',
  qty integer not null default 1 check (qty > 0),
  item_id bigint references public.inventory_items(id) on delete set null,
  barcode text not null default '',
  model text not null default '',
  partner text not null default '',
  store text not null default '',
  reason text not null default '',
  note text not null default '',
  created_at timestamptz not null default now()
);

alter table public.inventory_categories enable row level security;
alter table public.inventory_items enable row level security;
alter table public.inventory_transactions enable row level security;

drop policy if exists "authenticated shared categories" on public.inventory_categories;
create policy "authenticated shared categories" on public.inventory_categories
  for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

drop policy if exists "authenticated shared inventory" on public.inventory_items;
create policy "authenticated shared inventory" on public.inventory_items
  for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

drop policy if exists "authenticated shared transactions" on public.inventory_transactions;
create policy "authenticated shared transactions" on public.inventory_transactions
  for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

insert into public.inventory_categories(name)
values ('포스'),('백업'),('멀티패드'),('프린트'),('태블릿'),('토스프론트')
on conflict (name) do nothing;

-- Enable Realtime for all tables; skip any table already added to the publication.
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='inventory_categories') then
    execute 'alter publication supabase_realtime add table public.inventory_categories';
  end if;
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='inventory_items') then
    execute 'alter publication supabase_realtime add table public.inventory_items';
  end if;
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='inventory_transactions') then
    execute 'alter publication supabase_realtime add table public.inventory_transactions';
  end if;
end $$;
